export type PixelIconName = keyof typeof SPRITES;

type Props = {
  name: PixelIconName;
  size?: number;
  className?: string;
};

export function PixelIcon({ name, size = 16, className }: Props) {
  const rows = SPRITES[name] as readonly string[];
  const h = rows.length;
  const w = rows[0].length;
  const rects: ReactElement[] = [];

  for (let y = 0; y < h; y++) {
    const row = rows[y];
    let x = 0;
    while (x < w) {
      const ch = row[x];
      if (ch === ".") {
        x += 1;
        continue;
      }
      let run = 1;
      while (x + run < w && row[x + run] === ch) run += 1;
      rects.push(
        <rect
          key={`${y}-${x}`}
          x={x}
          y={y}
          width={run}
          height={1}
          fill={ch === "o" ? "var(--accent)" : "currentColor"}
        />,
      );
      x += run;
    }
  }

  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {rects}
    </svg>
  );
}
